    m.ec("Vint1cm", "0.5*Vint*LT1", "kgf", "Viga interior, tramo 1", doc=16074)
    m.ec("Vint2cm", "0.5*Vint*LT2", "kgf", "Viga interior, tramo 2", doc=16074)
