    m.dato("LT2", 18, "m", "Longitud del tramo 2")
    m.dato("Vext", 1637, "kgf/m", "Carga muerta de viga exterior")
    m.dato("Vint", 1786, "kgf/m", "Carga muerta de viga interior")
