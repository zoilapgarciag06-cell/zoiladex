    m.ec("P3r", "P3*0.5", "kgf", "Eje P3", doc=7257.478)
    m.sec("Reacción de la pila debido a carga viva")
    m.ec("RP1", "P1r*(LT1-L1e)/LT1", "kgf", "Debido a P1", doc=1384.24)
