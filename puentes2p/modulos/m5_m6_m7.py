    m.dato("HVCin", 2.1, "m", "Altura de viga cabezal en la cara de la columna")
    m.dato("VVC", 3.5, "m", "Volado de la viga cabezal")
    m.dato("ADp", 2.4, "m", "Ancho / diámetro de pila")
    m.dato("Sv", 2.0, "m", "Separación entre vigas")
    m.dato("DV1vol", 0.7, "m", "Viga 1 (exterior) al extremo de la viga cabezal")
    m.dato("Dca", 1.8, "m", "Distancia entre ejes de ruedas del camión")
    m.dato("Derint", 1.5, "m", "Eje de viga cabezal a línea de ruedas interior")
    m.sec("Distribución de carga viva")
    m.ec("V2ext", "w*(2*Sv-(Derint+Dca))/Sv", "kgf", "Línea de ruedas exterior: viga interior", doc=4962.54)
    m.ec("V1ext", "w-V2ext", "kgf", "Línea de ruedas exterior: viga exterior", doc=9216.15)
